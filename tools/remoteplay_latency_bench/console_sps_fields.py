from av.bitstream import BitStreamFilterContext
for name,codec,data in (('H.264 header',"h264",h264),('H.265 header',"hevc",h265)):
    lines.clear()
    ctx = av.CodecContext.create(codec,'r')
    bsf = BitStreamFilterContext('trace_headers', codec)
    p = av.Packet(data)
    list(bsf.filter(p))
    want = re.compile(r'(profile_idc|level_idc|pic_order_cnt_type|max_num_ref_frames|vui_parameters_present_flag|bitstream_restriction_flag|max_num_reorder_frames|max_dec_frame_buffering|sps_max_num_reorder_pics|sps_max_dec_pic_buffering|sps_max_latency_increase|pic_width|pic_height|general_profile_idc|general_level_idc|bit_depth_luma|num_units_in_tick|time_scale|log2_max_pic_order_cnt_lsb)')
    print('==',name, 'trace lines:',len(lines))
    for l in lines:
        if want.search(l): print('  ',re.sub(r'\s+',' ',l.strip())[-90:])
